"""Section 4.5, equations 12-15: one whole-constitution vote per trajectory."""

import re
from collections import Counter
from typing import Any

from pydantic import Field, create_model

from caiso.blocks.utils import block_strength
from caiso.prompts import entry as prompt_entry
from caiso.core.content_filter import ContentFilteredError, record_skip
from caiso.core.recovery import ModelResponseError
from caiso.core.serialization import Record, canonical, plain, save_json
from caiso.providers.base import messages


class BlockVote(Record):
    block_id: str
    brief_justification: str


class BlockVoteRecord(BlockVote):
    """Saved evidence, attached by CAISO rather than generated by the judge."""

    trajectory: dict[str, Any] | None = None  # Older saved votes have no embedded trajectory.


class BlockSelection(Record):
    selected: str
    scores: dict[str, float]
    votes: list[BlockVoteRecord]
    strengths: dict[str, float]
    blocks: dict[str, list[str]] = Field(default_factory=dict)
    optimization_history: dict[str, Any] = Field(default_factory=dict)


def _block_label(value):
    """Ignore only case, surrounding whitespace and common name separators."""
    return re.sub(r"[\s_-]+", " ", value.strip().casefold())


def _resolve_block(value, blocks):
    if value in blocks:
        return value
    label = _block_label(value)
    matches = {
        bid
        for bid, members in blocks.items()
        if label in {_block_label(name) for name in [bid, *members]}
    }
    if len(matches) == 1:
        return matches.pop()
    raise ModelResponseError(
        f"Judge selected an unknown or ambiguous block: {value!r}. "
        f"Allowed block IDs: {', '.join(blocks)}. Return exactly one of these IDs, "
        f"not a component name or explanation. Block membership: {canonical(blocks)}"
    )


def aggregate_votes(blocks, votes, effects):
    if not votes or not blocks:
        raise ValueError("Selection requires blocks and diagnostic trajectories")
    if any(v.block_id not in blocks for v in votes):
        raise ValueError("Judge selected an unknown block")
    counts = Counter(v.block_id for v in votes)
    scores = {bid: counts[bid] / len(votes) for bid in blocks}
    strengths = {bid: block_strength(members, effects) for bid, members in blocks.items()}
    selected = min(blocks, key=lambda bid: (-scores[bid], -strengths[bid], bid))
    return BlockSelection(
        selected=selected,
        scores=scores,
        votes=[BlockVoteRecord.model_validate(vote.model_dump()) for vote in votes],
        strengths=strengths,
        blocks=blocks,
    )


def select_block(
    constitution,
    trajectories,
    blocks,
    effects,
    providers,
    seed,
    role="block_selection",
    output=None,
    optimization_history=None,
):
    if not blocks or not trajectories:
        raise ModelResponseError("Selection requires blocks and unfiltered diagnostic trajectories")
    # Constrain strict API output to this partition. Local semantic validation below
    # also accepts unambiguous component names from older/non-strict backends.
    schema = create_model(
        "BlockVote",
        __base__=BlockVote,
        block_id=(
            str,
            Field(
                description="Select one listed block ID, not a component name.",
                json_schema_extra={"enum": list(blocks)},
            ),
        ),
    )
    votes = []

    def valid_vote(vote):
        resolved = _resolve_block(vote.block_id, blocks)
        if resolved != vote.block_id:
            providers.recovery.error(
                ModelResponseError(f"Resolved judge block label {vote.block_id!r} to {resolved!r}"),
                f"model:{role}",
                "normalized_block_vote",
                requested_block_id=vote.block_id,
                resolved_block_id=resolved,
            )
            vote = vote.model_copy(update={"block_id": resolved})
        return vote

    for i, trajectory in enumerate(trajectories):
        trajectory = plain(trajectory)  # One snapshot for both the judge and saved review evidence.
        try:
            vote = providers.complete(
                role,
                messages(
                    prompt_entry('method', 'block_selection.system').format(value_0=', '.join(blocks)),
                    canonical(
                        {
                            "constitution": constitution.principles,
                            "trajectory": trajectory,
                            "blocks": blocks,
                            "optimization_history": optimization_history or {},
                        }
                    ),
                ),
                seed=seed + i,
                schema=schema,
                validate=valid_vote,
            )
        except ContentFilteredError as error:
            record_skip(providers, error, "block_selection", example_id=trajectory.get("input_id"))
            continue
        votes.append(
            BlockVoteRecord(
                block_id=vote.block_id,
                brief_justification=vote.brief_justification,
                trajectory=trajectory,
            )
        )
    if not votes:
        raise ModelResponseError("No unfiltered diagnostic votes remain for block selection")
    selection = aggregate_votes(blocks, votes, effects)
    selection.optimization_history = plain(optimization_history or {})
    if output:
        save_json(output, selection)
    return selection
